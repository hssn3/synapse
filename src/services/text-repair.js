// واژه‌های سالمی که با «می/نمی» شروع می‌شوند و نباید شکسته شوند
const MI_SAFE = new Set(['میز', 'میان', 'میانه', 'میانگین', 'میلاد', 'میکروب', 'میکروبی',
  'میدان', 'میوه', 'میهمان', 'میل', 'میلی', 'میکرو', 'میکسر', 'مینا', 'میخ', 'میر',
  'میزان', 'میلیون', 'میلیارد', 'میراث', 'میکروبیال', 'میکروسکوپ', 'میکروسکوپی',
  'میدانی', 'میله', 'میانجی', 'مینیمم', 'میکروبیولوژی', 'نمیه']);
// واژه‌هایی که به «ها» ختم می‌شوند ولی جمع نیستند
const HA_SAFE = new Set(['تنها', 'رها', 'بها', 'گیاه', 'ماه', 'راه', 'شاه', 'کوتاه',
  'دستگاه', 'آگاه', 'سیاه', 'اشتباه', 'نگاه', 'گناه', 'پناه', 'همراه', 'جایگاه',
  'دیدگاه', 'پایگاه', 'کارگاه', 'زایشگاه', 'درمانگاه', 'آزمایشگاه', 'فرودگاه',
  'خوابگاه', 'اقامتگاه', 'پژوهشگاه', 'دانشگاه', 'بها', 'رفاه', 'اشتها', 'ابتلا',
  'اشتباه', 'گواه', 'شبیه', 'وجه', 'توجه', 'مواجه', 'فقه', 'وجهه']);

// پسوندهای ترکیبیِ پرکاربرد که استخراج‌گر به واژه چسبانده است
// (برنامهریزی ← برنامه‌ریزی، طبقهبندی ← طبقه‌بندی).
// «ای» عمداً نیست: «حرفهای» هم می‌تواند «حرفه‌ای» باشد هم «حرف‌های»،
// و حدس‌زدنش یعنی خرابیِ تازه.
const SUFFIX = /^(.{2,}?)(ریزی|سازی|بندی|گیری|دهی|پذیری|نویسی|گذاری|برداری|بردار|کنندگان|کننده|نشده|شده|محور|مدار)$/;

function fixZwnj(text) {
  return String(text).replace(/[؀-ۿ‌]+/g, (w) => {
    if (w.indexOf(ZWNJ) !== -1) return w;          // از قبل نیم‌فاصله دارد
    // می/نمی + فعل
    let m = /^(نمی|می)(.{3,})$/.exec(w);
    if (m && !MI_SAFE.has(w)) return m[1] + ZWNJ + m[2];
    // پسوند جمعِ ها/های/هایی — «ه»ی پایانیِ ستاک مانعی نیست
    // (کمیتهها ← کمیته‌ها)، فقط مصوت‌های بلند استثنا می‌شوند.
    m = /^(.{3,})(هایی|های|ها)$/.exec(w);
    if (m && !HA_SAFE.has(w) && !/[اآو]$/.test(m[1])) return m[1] + ZWNJ + m[2];
    // ترکیب‌های چسبیده
    m = SUFFIX.exec(w);
    if (m && m[1].length >= 3) return m[1] + ZWNJ + m[2];
    return w;
  });
}

/** ترمیم یک رشته: اول واژه‌های تأییدشده، بعد نیم‌فاصله */
function repair(text) {
  if (typeof text !== 'string' || !text) return text;
  // «حرف فارسی» را صریح تعریف می‌کنیم. نکته‌ی ریز ولی مهم: ویرگول فارسی «،»
  // (U+060C) و «؛» و «؟» داخل همان بلوک یونیکد عربی‌اند، پس اگر کل بلوک را
  // «حرف» بگیریم، «اطالعات،» یک واژه‌ی واحد می‌شود و هیچ‌وقت تطبیق نمی‌خورد.
  const L = '\u0621-\u063A\u0640-\u064A\u0654\u0655\u067E\u0686\u0698\u06A9\u06AF\u06BE\u06C0\u06CC\u06F0-\u06F9\u200c';
  const HARAKAT = '\u064B-\u0652';
  const re = new RegExp('[' + L + HARAKAT + ']+', 'g');
  const look = (k) => Object.prototype.hasOwnProperty.call(WORDS, k) ? WORDS[k] : null;
  let out = text.replace(re, (chunk) => {
    // اول خودِ واژه با اعرابش. اگر همین جواب داد، هیچ چیزی جدا و دوباره
    // چسبانده نمی‌شود — و همان‌جا از باگِ تکرارِ اعراب جلو گرفته می‌شود.
    let hit = look(chunk);
    if (hit !== null) return hit;

    const m = new RegExp('^([' + HARAKAT + ']*)([' + L + ']*?)([' + HARAKAT + ']*)$').exec(chunk);
    const pre = m ? m[1] : '', core = m ? m[2] : chunk, post = m ? m[3] : '';
    // بعضی واژه‌ها از قبل نیم‌فاصله دارند («مملول‌های»)؛ کلیدِ نگاشت بدون
    // نیم‌فاصله است، پس شکل بدون‌نیم‌فاصله هم امتحان می‌شود.
    const bare = core.split(ZWNJ).join('');
    hit = look(core);
    if (hit === null && bare !== core) hit = look(bare);
    if (hit === null) return chunk;
    // اعرابِ جداشده را فقط وقتی برمی‌گردانیم که جایگزین خودش آن را ندارد.
    // بدون این شرط «الزاما ← الزاماً» در هر اجرا یک تنوین دیگر می‌گرفت و
    // ترمیم هرگز به نقطه‌ی ثابت نمی‌رسید (در تست تکرار دیده شد).
    const tail = (post && hit.slice(-post.length) === post) ? '' : post;
    return pre + hit + tail;
  });
  out = fixZwnj(out);
  return out;
}

/** شمارش تغییرها بدون اعمال — برای گزارش */
function preview(text) {
  const before = String(text || '');
  const after = repair(before);
  if (before === after) return null;
  return { before, after };
}

/**
 * واژه‌های به‌هم‌چسبیده (دسته‌ی «و») — عمداً ترمیم نمی‌شوند.
 * حدس‌زدنِ مرزِ واژه‌ها یعنی ساختنِ متنی که در کتاب نیست، و در سندی که
 * قرار است به ارزیاب نشان داده شود این بدتر از خودِ خرابی است.
 * این تابع فقط فهرستشان می‌کند تا کاربر بداند کدام سنجه‌ها را باید دستی
 * از روی کتاب مرجع اصلاح کند.
 */
function findGlued(text, minLen) {
  const min = minLen || 22;
  const out = [];
  String(text || '').replace(/[\u0621-\u063A\u0640-\u064A\u067E\u0686\u0698\u06A9\u06AF\u06CC\u200c]+/g, (w) => {
    if (w.split(ZWNJ).join('').length >= min) out.push(w);
    return w;
  });
  return out;
}

/* ---------- ز: رشته‌های لاتینِ وارونه ---------- */
/**
 * استخراج‌گرِ PDF هر رشته‌ی لاتین را به ترتیبِ *دیداریِ* راست‌به‌چپ بیرون داده،
 * یعنی حروفش وارونه‌اند: «erutluC tsuJ» همان «Just Culture» است، «UCIN» همان
 * «NICU»، «AEMF» همان «FMEA» و «TRAMS» همان «SMART». شمارشِ کلِ کتاب نشان داد
 * استثنا ندارد — هر واژه‌ی لاتینی که در متنِ سنجه‌ها هست وارونه است.
 *
 * چرا عمداً جزوِ repair() نیست: وارونه‌کردن، خودش وارونه‌ی خودش است. repair() در
 * هر بوت روی همه‌ی ردیف‌ها اجرا می‌شود، پس اگر این کار آنجا بود، هر بار متن را
 * برعکس می‌کرد و «Just Culture» یک بوت درست و بوت بعد دوباره خراب می‌شد. این
 * تابع باید دقیقاً یک بار روی هر دیتابیس اجرا شود و اجرایش با نشانه در
 * platform_settings قفل می‌شود.
 */
function reverseLatinRuns(text) {
  if (typeof text !== 'string' || !text) return text;
  // کلِ عبارت یک‌جا برگردانده می‌شود، نه تک‌تکِ واژه‌ها. چون وارونگی *دیداری*
  // بوده، هم حروف و هم ترتیبِ واژه‌ها برعکس شده‌اند: «erutluC tsuJ». اگر فقط
  // حروفِ هر واژه برگردد، «Culture Just» درمی‌آید — حروف درست، ترتیب غلط.
  // برگرداندنِ کلِ رشته هر دو را با هم درست می‌کند.
  //
  // مرزِ عبارت فقط تک‌فاصله‌ی بینِ دو واژه‌ی لاتین است؛ هر چیز دیگری (فارسی،
  // رقم، نقطه‌گذاری) رشته را می‌بندد تا متنِ فارسیِ اطراف جابه‌جا نشود.
  return text.replace(/[A-Za-z]{2,}(?: [A-Za-z]{2,})*/g,
    (m) => m.split('').reverse().join(''));
}

