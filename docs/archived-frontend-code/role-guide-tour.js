let rgStep=0;
function rgGo(i){
  const n=rgSections().length;
  rgStep=Math.max(0,Math.min(n-1,i));
  renderRoleGuide(true);
  try{ window.scrollTo({top:0,behavior:'smooth'}); }catch(e){ window.scrollTo(0,0); }
}

