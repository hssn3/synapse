const insertDomainStmt = db.prepare(`
  INSERT INTO checklist_domains (id, hospital_id, checklist_id, title, sort_order, created_at)
  VALUES (?, ?, ?, ?, ?, datetime('now'))
`);

const insertItemStmt = db.prepare(`
  INSERT INTO checklist_items (id, hospital_id, checklist_id, domain_id, question_text, answer_type, weight, sort_order, created_at, is_active)
  VALUES (?, ?, ?, ?, ?, ?, ?, ?, datetime('now'), 1)
`);

const updateChecklistStmt = db.prepare(`
  UPDATE checklists SET has_domains = 1, updated_at = datetime('now') WHERE id = ?
`);

let totalDomainsCreated = 0;
let totalItemsCreated = 0;

const seedAll = db.transaction(() => {
  for (const chk of emptyChecklists) {
    const data = getChecklistData(chk.checklist_code, chk.title);
    
    let domainOrder = 0;
    for (const d of data) {
      const domainId = crypto.randomUUID();
      insertDomainStmt.run(domainId, chk.hospital_id, chk.id, d.domain, domainOrder++);
      totalDomainsCreated++;

      let itemOrder = 0;
      for (const q of d.items) {
        const itemId = crypto.randomUUID();
        // Determine answer type: if question starts with 'آیا' -> yes_no or likert5
        const ansType = (itemOrder % 2 === 0) ? 'likert5' : 'yes_no';
        const weight = (itemOrder === 0) ? 2 : 1;
        insertItemStmt.run(itemId, chk.hospital_id, chk.id, domainId, q, ansType, weight, itemOrder++);
        totalItemsCreated++;
      }
    }

    updateChecklistStmt.run(chk.id);
  }
});

seedAll();

