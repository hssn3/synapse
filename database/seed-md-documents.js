function runMigration() {
  // مدارک
  const docIns = db.prepare(`INSERT INTO controlled_documents
    (id, hospital_id, doc_type, title, doc_code, purpose, scope, work_method, version_no, status)
    SELECT ?,?,?,?,?,?,?,?,?,? WHERE NOT EXISTS
    (SELECT 1 FROM controlled_documents WHERE hospital_id=? AND doc_code=?)`);
  let nd = 0;
  for (const d of DOCS) {
    const r = docIns.run(uid(), DEMO, d[0], d[1], d[2], d[4], d[5], d[6], d[7], d[8], DEMO, d[2]);
    if (r.changes) nd++;
  }
  console.log(`[Seed MD-Docs] ${nd} مدرک`);

  // خطاها
  let ne = 0;
  for (const e of ERRORS) {
    const ex = db.prepare('SELECT id FROM medical_error_reports WHERE hospital_id=? AND tracking_code=?').get(DEMO, e[3]);
    if (!ex) {
      db.prepare(`INSERT INTO medical_error_reports
        (id, hospital_id, error_category, description, severity, department, status, tracking_code, needs_rca, rca_text, is_confidential)
        VALUES (?,?,?,?,?,?,'new',?,1,?,1)`).run(uid(), DEMO, e[0], e[1], e[2], e[3] === 'ERR-MD-140306' ? 'زنان' : (e[3].includes('58321') ? 'اورژانس' : 'ICU'), e[3], e[4]);
      ne++;
    }
  }
  console.log(`[Seed MD-Errors] ${ne} گزارش خطا`);

  // دانش
  const kIns = db.prepare(`INSERT INTO assistant_knowledge (id, hospital_id, title, content, source_type, status)
    SELECT ?,?,?,?,'manual','confirmed' WHERE NOT EXISTS
    (SELECT 1 FROM assistant_knowledge WHERE hospital_id=? AND title=?)`);
  let nk = 0;
  for (const k of KNOWLEDGE) {
    const r = kIns.run(uid(), DEMO, k[0], k[1], DEMO, k[0]);
    if (r.changes) nk++;
  }
  console.log(`[Seed MD-Knowledge] ${nk} دانش`);

  // شاخص‌ها
  let nkp = 0;
  for (const k of KPIS) {
    const ex = db.prepare('SELECT id FROM hospital_kpis WHERE hospital_id=? AND code=?').get(DEMO, k[0]);
    if (!ex) {
      db.prepare(`INSERT INTO hospital_kpis (id, hospital_id, code, title, category, target_value, definition, is_active)
        VALUES (?,?,?,?,?,?,?,1)`).run(uid(), DEMO, k[0], k[1], k[2], k[3], k[4]);
      nkp++;
    }
  }
  console.log(`[Seed MD-KPIs] ${nkp} شاخص`);

  // چک‌لیست‌ها
  const cIns = db.prepare(`INSERT INTO checklists (id, hospital_id, title, checklist_code, status)
    SELECT ?,?,?,?,'active' WHERE NOT EXISTS
    (SELECT 1 FROM checklists WHERE hospital_id=? AND title=?)`);
  let nc = 0;
  for (const c of CHECKLISTS) {
    const r = cIns.run(uid(), DEMO, c[0], c[1], DEMO, c[0]);
    if (r.changes) nc++;
  }
  console.log(`[Seed MD-Checklists] ${nc} چک‌لیست`);

  // تجهیزات
  const aIns = db.prepare(`INSERT INTO facility_assets (id, hospital_id, asset_code, title, category, manufacturer, location, status)
    SELECT ?,?,?,?,?,?,?,'active' WHERE NOT EXISTS
    (SELECT 1 FROM facility_assets WHERE hospital_id=? AND asset_code=?)`);
  let na = 0;
  for (const a of ASSETS) {
    const r = aIns.run(uid(), DEMO, a[0], a[1], 'تجهیزات پزشکی', a[2], a[4], DEMO, a[0]);
    if (r.changes) na++;
  }
  console.log(`[Seed MD-Assets] ${na} تجهیز`);
}

