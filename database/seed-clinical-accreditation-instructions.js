function runSeed() {
  console.log('[Seed Clinical Docs] Starting clinical accreditation instructions and checklists seed...');

  // دریافت تمام بیمارستان‌ها
  const hospitals = db.prepare('SELECT id, name FROM hospitals').all();
  if (!hospitals || hospitals.length === 0) {
    console.log('[Seed Clinical Docs] No hospitals found. Skipping.');
    return;
  }

  const selectDoc = db.prepare('SELECT id FROM controlled_documents WHERE hospital_id = ? AND doc_code = ?');
  const insertDoc = db.prepare(`
    INSERT INTO controlled_documents (
      id, hospital_id, doc_type, title, doc_code, responsible_person,
      prepared_date, last_review_date, issue_date, purpose, scope,
      legal_references, definitions, resources, related_staff,
      monitoring_method, work_method, decree_text, status, version_no,
      created_at, updated_at
    ) VALUES (
      ?, ?, 'instruction', ?, ?, ?,
      '2026-01-15', '2026-06-20', '2026-07-01', ?, ?,
      ?, ?, ?, ?,
      ?, ?, ?, 'approved', 1,
      datetime('now'), datetime('now')
    )
  `);

  const selectSignoff = db.prepare('SELECT id FROM document_signoffs WHERE document_id = ? AND signoff_role = ?');
  const insertSignoff = db.prepare(`
    INSERT INTO document_signoffs (
      id, hospital_id, document_id, person_name, position, signoff_role, signed_at, created_at
    ) VALUES (?, ?, ?, ?, ?, ?, datetime('now'), datetime('now'))
  `);

  let addedDocs = 0;
  let addedSignoffs = 0;

  for (const h of hospitals) {
    const hId = h.id;

    for (const doc of CLINICAL_DOCS) {
      const existing = selectDoc.get(hId, doc.code);
      let docId;
      if (!existing) {
        docId = crypto.randomUUID();
        insertDoc.run(
          docId, hId, doc.title, doc.code, doc.resp,
          doc.purpose, doc.scope, doc.ref, doc.def, doc.res, doc.staff,
          doc.mon, doc.work, doc.decree
        );
        addedDocs++;
      } else {
        docId = existing.id;
      }

      // امضاکنندگان استاندارد بالینی
      const signers = [
        { name: doc.resp, pos: 'مسئول تدوین و دبیر کمیته تخصصی', role: 'prepared' },
        { name: 'دکتر علیرضا محمدی', pos: 'مدیر بهبود کیفیت و اعتباربخشی', role: 'reviewed' },
        { name: 'دکتر محمدرضا حسینی', pos: 'رئیس بیمارستان', role: 'approved' }
      ];

      for (const s of signers) {
        const existingSign = selectSignoff.get(docId, s.role);
        if (!existingSign) {
          insertSignoff.run(crypto.randomUUID(), hId, docId, s.name, s.pos, s.role);
          addedSignoffs++;
        }
      }
    }
  }

  console.log(`[Seed Clinical Docs] Controlled Docs: Added ${addedDocs} documents, ${addedSignoffs} signoffs.`);

  // ثبت چک‌لیست‌های بالینی
  const selectChkl = db.prepare('SELECT id FROM checklists WHERE hospital_id = ? AND checklist_code = ?');
  const insertChkl = db.prepare(`
    INSERT INTO checklists (
      id, hospital_id, title, checklist_code, completion_type, purpose,
      has_domains, has_baseline, is_public, baseline_info, status,
      cadence, is_example, version_no, created_at, updated_at
    ) VALUES (
      ?, ?, ?, ?, 'per_department', ?,
      1, 0, 0, null, 'active',
      ?, 1, 1, datetime('now'), datetime('now')
    )
  `);

  const selectDomain = db.prepare('SELECT id FROM checklist_domains WHERE checklist_id = ? AND title = ?');
  const insertDomain = db.prepare(`
    INSERT INTO checklist_domains (id, hospital_id, checklist_id, title, sort_order, created_at)
    VALUES (?, ?, ?, ?, ?, datetime('now'))
  `);

  const selectItem = db.prepare('SELECT id FROM checklist_items WHERE checklist_id = ? AND question_text = ?');
  const insertItem = db.prepare(`
    INSERT INTO checklist_items (id, hospital_id, checklist_id, domain_id, question_text, answer_type, weight, sort_order, is_active, created_at)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, 1, datetime('now'))
  `);

  let addedChecklists = 0;
  let addedDomains = 0;
  let addedItems = 0;

  for (const h of hospitals) {
    const hId = h.id;

    for (const chk of CLINICAL_CHECKLISTS) {
      let chkId;
      const existingChk = selectChkl.get(hId, chk.code);
      if (!existingChk) {
        chkId = crypto.randomUUID();
        insertChkl.run(chkId, hId, chk.title, chk.code, chk.purpose, chk.cadence);
        addedChecklists++;
      } else {
        chkId = existingChk.id;
      }

      let dSort = 0;
      for (const dom of chk.domains) {
        let domainId;
        const existingDom = selectDomain.get(chkId, dom.title);
        if (!existingDom) {
          domainId = crypto.randomUUID();
          insertDomain.run(domainId, hId, chkId, dom.title, dSort++);
          addedDomains++;
        } else {
          domainId = existingDom.id;
        }

        let iSort = 0;
        for (const it of dom.items) {
          const existingIt = selectItem.get(chkId, it.q);
          if (!existingIt) {
            insertItem.run(crypto.randomUUID(), hId, chkId, domainId, it.q, it.type, it.weight, iSort++);
            addedItems++;
          }
        }
      }
    }
  }

  console.log(`[Seed Clinical Docs] Checklists: Added ${addedChecklists} checklists, ${addedDomains} domains, ${addedItems} items.`);
  console.log('[Seed Clinical Docs] ✅ Completed successfully.');
}

if (require.main === module) {
  runSeed();
  process.exit(0);
}

module.exports = { runSeed };
