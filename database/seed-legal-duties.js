function runMigration() {
  console.log('[Seed LegalDuties] Starting...');
  try {
    db.exec(`CREATE TABLE IF NOT EXISTS role_legal_duties (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      hospital_id TEXT,                 -- NULL یعنی بندِ پیش‌فرضِ سراسری
      role_code   TEXT NOT NULL,
      duty_text   TEXT NOT NULL,
      source      TEXT,
      source_url  TEXT,
      sort_order  INTEGER DEFAULT 0,
      is_custom   INTEGER DEFAULT 0,    -- ۱ یعنی خودِ بیمارستان اضافه/ویرایش کرده
      created_at  TEXT DEFAULT (datetime('now'))
    )`);
    db.exec(`CREATE INDEX IF NOT EXISTS idx_legal_duties_role
             ON role_legal_duties(role_code, hospital_id)`);

    const exists = db.prepare(
      `SELECT id FROM role_legal_duties
       WHERE role_code = ? AND duty_text = ? AND hospital_id IS NULL`);
    const ins = db.prepare(
      `INSERT INTO role_legal_duties (hospital_id, role_code, duty_text, source, source_url, sort_order)
       VALUES (NULL, ?, ?, ?, ?, ?)`);

    let added = 0;
    for (const [role, list] of Object.entries(LEGAL)) {
      list.forEach(([text, srcKey], i) => {
        if (exists.get(role, text)) return;      // از قبل هست — دست نمی‌زنیم
        ins.run(role, text, IUMS, SRC[srcKey] || null, i);
        added++;
      });
    }
    const total = db.prepare('SELECT COUNT(*) n FROM role_legal_duties').get().n;
    console.log(`[Seed LegalDuties] ✅ ${added} بند جدید درج شد (مجموع ${total} بند برای ${Object.keys(LEGAL).length} سمت)`);
  } catch (err) {
    console.error('[Seed LegalDuties] ❌ Failed:', err.message);
    throw err;
  }
}

if (require.main === module) {
  runMigration();
  process.exit(0);
}
module.exports = { runMigration, LEGAL };
