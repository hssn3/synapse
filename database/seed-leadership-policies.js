function runSeed() {
  console.log('[Seed Leadership Policies] Starting...');
  // دریافت بیمارستان فعال (بیمارستان شماره یک نمونه)
  const hospitals = db.prepare('SELECT id, name FROM hospitals ORDER BY created_at ASC').all();
  if (!hospitals.length) {
    console.log('[Seed Leadership Policies] No hospital found, skipping.');
    return;
  }
  const hId = hospitals[0].id;
  console.log(`[Seed Leadership Policies] Seeding for hospital: ${hospitals[0].name} (${hId})`);

  const selectStmt = db.prepare('SELECT id FROM controlled_documents WHERE hospital_id = ? AND doc_code = ?');
  const insertStmt = db.prepare(`
    INSERT INTO controlled_documents (
      id, hospital_id, doc_type, title, doc_code, responsible_person,
      prepared_date, last_review_date, issue_date, purpose, scope,
      legal_references, definitions, resources, related_staff,
      monitoring_method, work_method, decree_text, status, version_no,
      is_example, created_at, updated_at
    ) VALUES (
      ?, ?, 'policy', ?, ?, ?,
      ?, ?, ?, ?, ?,
      ?, ?, ?, ?,
      ?, ?, ?, 'active', 1,
      0, datetime('now'), datetime('now')
    )
  `);

  let added = 0;
  for (const pol of LEADERSHIP_POLICIES) {
    const existing = selectStmt.get(hId, pol.doc_code);
    if (!existing) {
      const docId = crypto.randomUUID();
      insertStmt.run(
        docId, hId, pol.title, pol.doc_code, pol.responsible_person,
        pol.prepared_date, pol.last_review_date, pol.issue_date, pol.purpose, pol.scope,
        pol.legal_references, pol.definitions, pol.resources, pol.related_staff,
        pol.monitoring_method, pol.work_method, pol.decree_text
      );
      added++;
      console.log(`[Seed Leadership Policies] + [${pol.doc_code}] ${pol.title}`);
    } else {
      console.log(`[Seed Leadership Policies] = [${pol.doc_code}] already exists`);
    }
  }

  console.log(`[Seed Leadership Policies] ✅ Finished. Added ${added} new leadership policies.`);
}

if (require.main === module) {
  runSeed();
  process.exit(0);
}

