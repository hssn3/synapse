function runMigration() {
  const ins = db.prepare(`INSERT OR IGNORE INTO drug_formulary
    (id, hospital_id, generic_name, brand_name, local_code, dosage_form, strength,
     is_vital, is_essential, is_high_alert, is_lasa, is_refrigerated, is_narcotic, is_cytotoxic,
     storage_note, note, is_active)
    VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,1)`);
  let n = 0;
  DRUGS.forEach((d, i) => {
    const code = 'MD-' + String(i + 1).padStart(3, '0');
    const r = ins.run(crypto.randomUUID(), DEMO, d[0], d[1], code, d[2], d[3],
      0, 0, d[4].ha ? 1 : 0, d[4].lasa ? 1 : 0, d[4].ref ? 1 : 0, d[4].nar ? 1 : 0, d[4].cyto ? 1 : 0,
      d[5] || null, d[6] || null);
    if (r.changes) n++;
  });
  console.log(`[Seed MD-Formulary] ${n} قلم جدید (کد MD-*)`);
}

