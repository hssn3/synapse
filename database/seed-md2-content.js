function runMigration() {
  const docIns = db.prepare(`INSERT INTO controlled_documents
    (id, hospital_id, doc_type, title, doc_code, scope, work_method, version_no, status)
    SELECT ?,?,?,?,?,?,?,?,? WHERE NOT EXISTS
    (SELECT 1 FROM controlled_documents WHERE hospital_id=? AND doc_code=?)`);
  let nd = 0;
  for (const d of DOCS) {
    if (docIns.run(uid(), DEMO, d[0], d[1], d[2], d[4], d[5], d[6], d[7], DEMO, d[2]).changes) nd++;
  }
  console.log(`[Seed MD2-Docs] ${nd} مدرک`);

  let ne = 0;
  for (const e of ERRORS) {
    const ex = db.prepare('SELECT id FROM medical_error_reports WHERE hospital_id=? AND tracking_code=?').get(DEMO, e[4]);
    if (!ex) {
      db.prepare(`INSERT INTO medical_error_reports
        (id, hospital_id, error_category, description, severity, department, status, tracking_code, needs_rca, rca_text, is_confidential)
        VALUES (?,?,?,?,?,?,'new',?,1,?,1)`).run(uid(), DEMO, e[0], e[1], e[2], e[3], e[4], e[5]);
      ne++;
    }
  }
  console.log(`[Seed MD2-Errors] ${ne} خطا`);

  const etIns = db.prepare(`INSERT OR IGNORE INTO medical_error_types (code, title, category) VALUES (?,?,?)`);
  let nt = 0;
  for (const t of ETYPES) { if (etIns.run(t[0], t[1], t[2]).changes) nt++; }
  console.log(`[Seed MD2-ErrTypes] ${nt} نوع`);

  let nkp = 0;
  for (const k of KPIS) {
    const ex = db.prepare('SELECT id FROM hospital_kpis WHERE hospital_id=? AND code=?').get(DEMO, k[0]);
    if (!ex) {
      db.prepare(`INSERT INTO hospital_kpis (id, hospital_id, code, title, target_value, definition, is_active)
        VALUES (?,?,?,?,?,?,1)`).run(uid(), DEMO, k[0], k[1], k[2], k[3]);
      nkp++;
    }
  }
  console.log(`[Seed MD2-KPIs] ${nkp} شاخص`);

  const kIns = db.prepare(`INSERT INTO assistant_knowledge (id, hospital_id, title, content, source_type, status)
    SELECT ?,?,?,?,'manual','confirmed' WHERE NOT EXISTS
    (SELECT 1 FROM assistant_knowledge WHERE hospital_id=? AND title=?)`);
  let nk = 0;
  for (const k of KNOWLEDGE) { if (kIns.run(uid(), DEMO, k[0], k[1], DEMO, k[0]).changes) nk++; }
  console.log(`[Seed MD2-Knowledge] ${nk} دانش`);

  const cIns = db.prepare(`INSERT INTO checklists (id, hospital_id, title, checklist_code, status)
    SELECT ?,?,?,?,'active' WHERE NOT EXISTS
    (SELECT 1 FROM checklists WHERE hospital_id=? AND title=?)`);
  let nc = 0;
  for (const c of CHECKLISTS) { if (cIns.run(uid(), DEMO, c[0], c[1], DEMO, c[0]).changes) nc++; }
  console.log(`[Seed MD2-Checklists] ${nc} چک‌لیست`);

  const aIns = db.prepare(`INSERT INTO facility_assets (id, hospital_id, asset_code, title, category, manufacturer, location, status)
    SELECT ?,?,?,?,?,?,?,'active' WHERE NOT EXISTS
    (SELECT 1 FROM facility_assets WHERE hospital_id=? AND asset_code=?)`);
  let na = 0;
  for (const a of ASSETS) { if (aIns.run(uid(), DEMO, a[0], a[1], 'تجهیزات پزشکی', a[2], a[3], DEMO, a[0]).changes) na++; }
  console.log(`[Seed MD2-Assets] ${na} تجهیز`);

  let ntr = 0;
  for (const t of TRAININGS) {
    const ex = db.prepare('SELECT id FROM training_needs WHERE hospital_id=? AND title=?').get(DEMO, t[0]);
    if (!ex) {
      db.prepare(`INSERT INTO training_needs (id, hospital_id, title, department, year) VALUES (?,?,?,?,?)`)
        .run(uid(), DEMO, t[0], t[1], t[2]);
      ntr++;
    }
  }
  console.log(`[Seed MD2-Training] ${ntr} نیاز`);

  let nf = 0;
  for (const f of FMEAS) {
    const ex = db.prepare('SELECT id FROM fmea_records WHERE hospital_id=? AND subject=?').get(DEMO, f[0]);
    if (!ex) {
      db.prepare(`INSERT INTO fmea_records
        (id, hospital_id, subject, reporting_department, failure_modes, root_causes, effects, existing_controls, recommended_actions)
        VALUES (?,?,?,?,?,?,?,?,?)`).run(uid(), DEMO, f[0], f[1], f[0], f[2], f[3], f[4], f[5]);
      nf++;
    }
  }
  console.log(`[Seed MD2-FMEA] ${nf} رکورد`);

  const cex = db.prepare("SELECT id FROM committees WHERE hospital_id=? AND name=?").get(DEMO, 'کارگروه آموزش به بیمار');
  if (!cex) {
    db.prepare(`INSERT INTO committees (id, hospital_id, name, committee_type, meeting_frequency)
      VALUES (?,?,?,?,?)`).run(uid(), DEMO, 'کارگروه آموزش به بیمار', 'education', 'فصلی');
    console.log('[Seed MD2-Committee] 1 کمیته');
  } else console.log('[Seed MD2-Committee] 0 کمیته');
}

if (require.main === module) { runMigration(); process.exit(0); }
module.exports = { runMigration };
